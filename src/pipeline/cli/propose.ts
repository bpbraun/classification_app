import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import Anthropic from "@anthropic-ai/sdk";
import { checkProposal } from "../../core/validator";
import type { Proposal } from "../../core/types";
import { AnthropicProposer, promptTemplateSha256 } from "../propose";
import { extractedSchema, proposalsFileSchema, type ProposalsFile } from "../../data/schema";
import { PATHS } from "./paths";

const DEFAULT_MODEL = "claude-sonnet-5-5";

if (existsSync(".env")) process.loadEnvFile(".env");
const apiKey = process.env.ANTHROPIC_API_KEY;
if (!apiKey) {
  console.error("Set ANTHROPIC_API_KEY in your shell or in .env (see .env.example).");
  process.exit(1);
}

const model = process.env.ANTHROPIC_MODEL || DEFAULT_MODEL;
const data = extractedSchema.parse(JSON.parse(await readFile(PATHS.extracted, "utf8")));
const proposer = new AnthropicProposer(new Anthropic({ apiKey }), model);

const proposals: Proposal[] = [];
for (const paragraph of data.exercise.paragraphs) {
  const proposal = await proposer.propose(data.guide, paragraph);
  const check = checkProposal(data.guide, proposal);
  const flags = check.findings.filter((f) => f.kind !== "supported").map((f) => f.kind);
  console.log(
    `${paragraph.id}: ${proposal.citedRuleIds.join(", ") || "(none)"}${flags.length ? `  [${flags.join(", ")}]` : ""}`,
  );
  proposals.push(proposal);
}

const file: ProposalsFile = proposalsFileSchema.parse({
  provenance: {
    kind: "model",
    description: `Generated by ${model} with temperature 0 from the committed prompt template.`,
    model,
    promptTemplateSha256: promptTemplateSha256(),
    sourceSha256: data.source.sha256,
    createdAt: new Date().toISOString(),
  },
  proposals,
});
await writeFile(PATHS.proposals, JSON.stringify(file, null, 2) + "\n");
console.log(`Wrote ${PATHS.proposals} (${proposals.length} proposals from ${model})`);
